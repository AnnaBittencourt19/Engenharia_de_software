public class EnsinoMain { // declaração de classe
    public static void main(String[] args) { //método main, onde o programa começa
        System.out.println("This is my first Java program");   // coloque a mensagem entre as aspas
    }
}
/*
O método main é uma parte crucial de um programa Java porque ele serve como o ponto de partida da execução.
Quando você executa um programa Java, a Java Virtual Machine (JVM) procura pelo método main para começar a executar o código.
Sem um método main, a JVM não saberia por onde começar.
 */